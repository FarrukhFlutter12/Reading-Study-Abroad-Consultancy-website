/**
 * Regenerates IMAGES-NEEDED.md from data/images.ts so the checklist can never
 * drift from the code.  Run:  node scripts/generate-images-doc.mjs
 *
 * data/images.ts is TypeScript, so rather than adding a build step we parse the
 * slot literals out of the source. Every slot has the same shape, which makes a
 * regex read safe here and keeps the project dependency-free.
 */

import fs from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const SRC = fs.readFileSync(path.join(ROOT, "data", "images.ts"), "utf8");

/* Pull each { src, alt, brief, size, maxKb } literal out of the manifest. */
const slotRe =
  /src:\s*(?:`([^`]+)`|"([^"]+)")\s*,\s*alt:\s*(?:`([^`]+)`|"([^"]+)")\s*,\s*brief:\s*(?:"((?:[^"\\]|\\.)*)"|`([^`]+)`)\s*,\s*size:\s*"([^"]+)"\s*,\s*maxKb:\s*(\d+)/g;

const slots = [];
let m;
while ((m = slotRe.exec(SRC)) !== null) {
  slots.push({
    src: m[1] ?? m[2],
    alt: m[3] ?? m[4],
    brief: (m[5] ?? m[6]).replace(/\\"/g, '"').replace(/\s+/g, " ").trim(),
    size: m[7],
    maxKb: Number(m[8]),
  });
}

/* The destination slots are generated by a helper, so expand the template. */
const COUNTRIES = [
  ["uk", "the United Kingdom", "Big Ben and the Houses of Parliament"],
  ["cyprus", "Cyprus", "Mediterranean coastline"],
  ["bulgaria", "Bulgaria", "Alexander Nevsky Cathedral, Sofia"],
  ["italy", "Italy", "The Colosseum, Rome"],
  ["lithuania", "Lithuania", "Vilnius old town"],
  ["malta", "Malta", "Valletta harbour"],
  ["south-korea", "South Korea", "Seoul skyline"],
  ["hungary", "Hungary", "The Hungarian Parliament, Budapest"],
  ["france", "France", "The Eiffel Tower, Paris"],
  ["turkey", "Turkey", "The Blue Mosque, Istanbul"],
];

const fixed = slots.filter((s) => !s.src.includes("${"));

const destinationRows = COUNTRIES.flatMap(([slug, name, landmark]) => [
  {
    src: `/images/destinations/${slug}.jpg`,
    size: "1600×900",
    maxKb: 150,
    query: `${landmark} landscape`,
    note: `Wide crop of ${landmark}. Leave the left third clear for the headline.`,
  },
  {
    src: `/images/destinations/${slug}-card.jpg`,
    size: "800×600",
    maxKb: 80,
    query: `${name} university campus students`,
    note: `Tighter crop that still reads at 400 px wide.`,
  },
]);

const QUERIES = {
  "/images/hero/main-hero.jpg": "diverse international students walking campus",
  "/images/hero/hero-mobile.jpg": "international students campus portrait",
  "/images/about/office-team.jpg": "advisor student desk documents office",
  "/images/about/counselling-session.jpg": "consultant meeting client laptop office",
  "/images/about/office-exterior.jpg": "— CLIENT PHOTO, do not use stock —",
  "/images/sections/students-group.jpg": "students studying together library campus",
  "/images/sections/graduation.jpg": "graduation caps thrown air celebration",
  "/images/sections/visa-documents.jpg": "passport documents desk flat lay",
  "/images/sections/lecture-hall.jpg": "university lecture hall professor students",
  "/images/sections/airport-departure.jpg": "student luggage airport terminal departure",
  "/images/sections/ielts-study.jpg": "student headphones studying english test",
};

const exists = (p) => fs.existsSync(path.join(ROOT, "public", p));
const tick = (p) => (exists(p) ? "✅" : "⬜");

const lines = [];
lines.push("# Images Needed");
lines.push("");
lines.push(
  "Every slot below is already wired into the code. Until a file exists the site",
  "renders a branded navy→gold panel in its place — nothing looks broken, so",
  "there is no rush and no half-finished state. Drop a file in at the exact path",
  "and it appears on the next deploy, with no code change.",
);
lines.push("");
lines.push("> Regenerate this file with `node scripts/generate-images-doc.mjs`.");
lines.push("");
lines.push("---");
lines.push("");
lines.push("## Sourcing rules");
lines.push("");
lines.push("**Use only these two sources.** Both allow commercial use with no attribution:");
lines.push("");
lines.push("- Unsplash — <https://unsplash.com>");
lines.push("- Pexels — <https://pexels.com>");
lines.push("");
lines.push("**Never use** Getty, Shutterstock, Freepik, or anything found through Google");
lines.push("Images. These carry licence risk that lands on the client, not the designer.");
lines.push("");
lines.push("### Four hard rules");
lines.push("");
lines.push(
  "1. **Download the file — never paste a link.** An external URL breaks when the",
  "   source deletes the image, and leaks your visitors' referrer data.",
);
lines.push(
  "2. **No university logos, crests or branded signage.** Showing a university's",
  "   mark implies an official partnership. Until written proof of partnership",
  "   exists, campus photography must be generic.",
);
lines.push(
  "3. **No stock faces on success stories.** A stock portrait beside a student",
  "   testimonial is misrepresentation. Use a real photo with written consent, or",
  "   an initial-letter avatar.",
);
lines.push(
  "4. **Cast for the audience.** This consultancy serves Pakistani students.",
  "   Prefer South Asian and visibly diverse students — a hero full of only",
  "   Northern-European faces reads as a template and costs you enquiries.",
);
lines.push("");
lines.push("---");
lines.push("");
lines.push("## Optimisation — do this before adding any file");
lines.push("");
lines.push("Pakistani students are mostly on 3G/4G with data caps. A 4 MB hero will cost");
lines.push("you more enquiries than a mediocre photo will.");
lines.push("");
lines.push("1. Resize to the dimensions in the table — no larger.");
lines.push("2. Convert to WebP at quality 80 (<https://squoosh.app>, free, in-browser).");
lines.push("3. Check it against the size budget below.");
lines.push("4. Save with the exact filename shown. Keep the `.jpg` name even for a");
lines.push("   WebP file if you prefer — or update the path in `data/images.ts`.");
lines.push("");
lines.push("Next.js re-encodes to AVIF/WebP and serves the right size per device, so the");
lines.push("budget is about the source file, not what the visitor downloads.");
lines.push("");
lines.push("---");
lines.push("");
lines.push("## Core images");
lines.push("");
lines.push("| ✓ | File | Size | Max | Search query | What makes a good pick |");
lines.push("|---|---|---|---|---|---|");
for (const s of fixed) {
  const q = QUERIES[s.src] ?? "";
  lines.push(
    `| ${tick(s.src)} | \`${s.src}\` | ${s.size} | ${s.maxKb} KB | \`${q}\` | ${s.brief} |`,
  );
}
lines.push("");
lines.push("---");
lines.push("");
lines.push("## Destination images");
lines.push("");
lines.push("Two per country: a wide hero and a tighter card crop.");
lines.push("");
lines.push("| ✓ | File | Size | Max | Search query | Note |");
lines.push("|---|---|---|---|---|---|");
for (const d of destinationRows) {
  lines.push(
    `| ${tick(d.src)} | \`${d.src}\` | ${d.size} | ${d.maxKb} KB | \`${d.query}\` | ${d.note} |`,
  );
}
lines.push("");
lines.push("---");
lines.push("");
lines.push("## Where photography must NOT go");
lines.push("");
lines.push("These surfaces need clean navy or white behind them. Photography here reduces");
lines.push("readability and costs conversions:");
lines.push("");
lines.push("- Form panels (contact, apply, free assessment)");
lines.push("- The FAQ accordion");
lines.push("- The six-step process timeline");
lines.push("- The stats band");
lines.push("");
lines.push("---");
lines.push("");
const done = [...fixed.map((s) => s.src), ...destinationRows.map((d) => d.src)].filter(exists).length;
const total = fixed.length + destinationRows.length;
lines.push(`**Progress: ${done} / ${total} images supplied.**`);
lines.push("");

fs.writeFileSync(path.join(ROOT, "IMAGES-NEEDED.md"), lines.join("\n"), "utf8");
console.log(`IMAGES-NEEDED.md written — ${total} slots, ${done} supplied.`);
